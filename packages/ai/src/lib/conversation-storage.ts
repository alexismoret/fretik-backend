const initializedSandboxes = new Set<string>();
const inFlightInits = new Map<string, Promise<void>>();
const backupChains = new Map<string, Promise<void>>();

const sleep = (ms: number): Promise<void> =>
  new Promise((resolve) => setTimeout(resolve, ms));

// ============================================================ //
// PATH UTILITIES                                                //
// ============================================================ //

const stripLeadingSlash = (path: string): string =>
  path.startsWith("/") ? path.replace(/^\/+/, "") : path;

const stripWorkspacePrefix = (path: string): string => {
  const stripped = stripLeadingSlash(path);
  const prefix = `${stripLeadingSlash(WORKSPACE_ROOT)}/`;
  return stripped.startsWith(prefix) ? stripped.slice(prefix.length) : stripped;
};

const toRelativeWorkspacePath = (path: string): string =>
  sanitizeSessionPath(stripWorkspacePrefix(path));

const isUnderBackupEligibleDir = (relativePath: string): boolean => {
  const head = relativePath.split("/")[0];
  if (head === undefined) return false;
  return BACKUP_ELIGIBLE_DIRS.includes(head);
};

/**
 * Resolve a user-supplied path to a `(relative, absolute)` pair under
 * `/workspace`, or `null` when the input would escape the sandbox via
 * `..` or absolute paths outside `/workspace`. Used by tools that
 * accept agent-supplied paths (`read`, `vision`, `presentFiles`,
 * `download_drive_document`) to enforce the sandbox boundary in a
 * single place.
 *
 * Accepts:
 *   - `attachments/foo.pdf`             → relative form
 *   - `/workspace/attachments/foo.pdf`  → absolute form, stripped
 *   - `foo.pdf`                          → flat basename, returned as-is
 *
 * Anything else (e.g. `/etc/passwd`, `../escape`) returns `null`. The
 * `relative` field is suitable for `readFile`/`writeFile` on the
 * façade; the `absolute` field is what the agent sees in tool output.
 */
export interface ResolvedWorkspacePath {
  /** Path relative to `/workspace`, e.g. `attachments/foo.pdf`. */
  relative: string;
  /** Absolute sandbox path, e.g. `/workspace/attachments/foo.pdf`. */
  absolute: string;
}

export const resolveWorkspacePath = (
  rawPath: string,
): ResolvedWorkspacePath | null => {
  if (rawPath.length === 0) return null;

  // Reject absolute paths that point outside /workspace before any
  // sanitisation strips the prefix.
  if (rawPath.startsWith("/")) {
    const stripped = stripLeadingSlash(rawPath);
    const wsPrefix = `${stripLeadingSlash(WORKSPACE_ROOT)}/`;
    if (
      !stripped.startsWith(wsPrefix) &&
      stripped !== stripLeadingSlash(WORKSPACE_ROOT)
    ) {
      return null;
    }
  }

  // Reject `..` traversal segments. Sanitisation downstream replaces
  // `.` / `..` characters but a literal `../escape` containing forbidden
  // characters would still pass — explicit rejection is clearer.
  for (const segment of rawPath.split("/")) {
    if (segment === "..") return null;
  }

  const relative = toRelativeWorkspacePath(rawPath);
  if (relative.length === 0) return null;

  return {
    relative,
    absolute: `${WORKSPACE_ROOT}/${relative}`,
  };
};

