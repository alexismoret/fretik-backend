/**
 * Sandbox-first conversation storage façade.
 *
 * Single source of truth for files visible to the chatbot agent during
 * a conversation. Every file lives directly in the conversation's
 * sandbox at `/workspace/...`. S3 mirrors the durable subset
 * (`attachments/`, `outputs/`) so a sandbox recreated after expiry
 * can be restored.
 *
 * Workspace layout (paths relative to `/workspace`):
 *
 *   attachments/   user uploads in this conversation       (R/W, S3-backed)
 *   outputs/       files generated by python/bash + persisted tool outputs (R/W, S3-backed)
 *     persisted/   large tool result envelopes (toolCallId.txt)
 *   drive/         Drive documents downloaded on demand    (R-only, NOT backed up)
 *   skills/        bundled skills pushed at first init     (R-only)
 *   context/       team/user context snapshots              (R-only, future)
 *   memory/        memory tool surface                      (R via tool, future)
 *
 * The Python skill loader (`skill_loader`) is pre-installed at
 * `/opt/fretik/skill_loader.py` by the E2B template build, exposed via
 * a `.pth` file in site-packages. The bundled skill bundles (the
 * SKILL.md + scripts/ + references/ trees) are pushed to
 * `/workspace/skills/` per-conversation by `bootstrapSandbox` below.
 *
 * Concurrency model — multi-replica @fretik/ai:
 *   1. **In-process fast path**: a `Set<sandboxId>` skips bootstrap
 *      when this replica has already done it.
 *   2. **In-process dedup**: parallel calls within a replica share a
 *      single bootstrap promise via `inFlightInits`.
 *   3. **Cross-replica safety**: a Redis lock keyed on `sandboxId`
 *      (`acquireSandboxBootstrapLock`) prevents two replicas from
 *      double-bootstrapping. Losers poll for the `.fretik-init`
 *      marker the winner writes when it's done.
 *   4. **Idempotent operations**: every step is rerun-safe — `mkdir
 *      -p`, file-overwrite write, and skip-on-exists S3 restore.
 *
 * S3 backup model:
 *   - Backups are FIRE-AND-FORGET. A `Map<key, Promise>` chain
 *     serialises uploads for the same `(conv, path)` pair so consecutive
 *     writes land in order on S3 (per-replica).
 *   - Cross-replica races on the same path use last-write-wins
 *     semantics (S3 putObject is atomic). Acceptable in dev; if it
 *     becomes a real problem a Redis lock per `(conv, path)` can be
 *     layered on later.
 */

