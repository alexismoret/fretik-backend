export interface AttachUserFileResult {
  /** Path relative to `/workspace` (e.g. `attachments/foo.pdf`). */
  path: string;
  /** Absolute sandbox path (`/workspace/attachments/foo.pdf`). */
  absolutePath: string;
}

/**
 * Attach a user-uploaded file to the conversation. Writes the bytes to
 * S3 only — the durable source of truth — and bumps the attachment
 * generation so a warm sandbox re-restores before its next code run.
 *
 * The sandbox is intentionally NOT touched here: `read` and the
 * extraction cache work straight off S3, so the common "attach + ask a
 * question" turn never pays an E2B round-trip. The file is lazily
 * restored into `/workspace/attachments/` by `ensureSandboxReady` the
 * first time `python`/`bash` actually needs the workspace (cold
 * bootstrap → `restoreFromS3`; warm sandbox → `reconcileAttachments`).
 *
 * The S3 upload is awaited synchronously so a downstream consumer that
 * presigns + fetches the object immediately (e.g. Mistral OCR) cannot
 * race the backup and see a 404.
 *
 * The filename is sanitised; the caller (chat-files upload service)
 * is expected to have already deduped against existing names.
 *
 * `contentType` should be the `file.type` from the multipart upload
 * boundary so Scaleway serves the object with the right Content-Type
 * (Mistral OCR otherwise can refuse the fetched blob).
 */
export const attachUserFile = async (
  conversationId: string,
  filename: string,
  bytes: Uint8Array | string,
  contentType?: string,
): Promise<AttachUserFileResult> => {
  const sanitisedFilename = sanitizeSessionPath(filename);
  const relativePath = `${WORKSPACE_DIRS.attachments}/${sanitisedFilename}`;
  const buffer =
    typeof bytes === "string" ? new TextEncoder().encode(bytes) : bytes;
  await uploadSessionFile(conversationId, relativePath, buffer, contentType);
  await bumpAttachmentGeneration(conversationId);
  return {
    path: relativePath,
    absolutePath: `${WORKSPACE_ROOT}/${relativePath}`,
  };
};

interface WriteFileOptions {
  /**
   * Content-Type for the S3 backup. Threaded down to `putObject` so
   * Scaleway serves the object with the proper MIME (otherwise it
   * defaults to `application/octet-stream`). Pass when known —
   * `file.type` from multipart uploads, `text/markdown` for sidecars.
   */
  contentType?: string;
  /**
   * If `true`, awaits the S3 backup before returning. Required when a
   * downstream step will presign + fetch the object immediately
   * (e.g. user attachments → OCR). Defaults to `false` (fire-and-
   * forget) for hot-path writes like sidecars and tool outputs.
   */
  awaitBackup?: boolean;
}

/**
 * Write arbitrary bytes to the sandbox at the given workspace-relative
 * path. Triggers an S3 backup for paths under `attachments/` or
 * `outputs/`. Used internally for OCR sidecars and persisted
 * tool-output envelopes.
 */
export const writeFile = async (
  conversationId: string,
  path: string,
  bytes: Uint8Array | string,
  options: WriteFileOptions = {},
): Promise<void> => {
  await ensureSandboxReady(conversationId);
  const buffer =
    typeof bytes === "string" ? new TextEncoder().encode(bytes) : bytes;
  const relativePath = toRelativeWorkspacePath(path);
  await writeSandboxFile(conversationId, relativePath, buffer);
  if (isUnderBackupEligibleDir(relativePath)) {
    if (options.awaitBackup) {
      await uploadSessionFile(
        conversationId,
        relativePath,
        buffer,
        options.contentType,
      );
    } else {
      queueS3Backup(conversationId, relativePath, buffer, options.contentType);
    }
  }
};

