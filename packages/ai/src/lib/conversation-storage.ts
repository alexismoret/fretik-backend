/**
 * Delete a file from S3 (the durable source of truth) and, only if a
 * sandbox currently exists for the conversation, from the workspace too.
 *
 * We deliberately do NOT call `ensureSandboxReady` here: a delete must
 * not trigger a cold E2B bootstrap (skills push + S3 restore) just to
 * remove a file that — under lazy hydration — may never have been
 * restored into the sandbox in the first place. The "does a sandbox
 * exist?" gate is the SHARED Redis registry, not in-process state, so it
 * holds across replicas: whichever replica serves the delete removes the
 * file from the one shared remote sandbox. When no sandbox exists the S3
 * delete alone is sufficient (nothing to re-restore — the object is
 * gone).
 *
 * Best-effort on both sides — a sandbox-side failure still attempts the
 * remote delete.
 */
export const deleteFile = async (
  conversationId: string,
  path: string,
): Promise<void> => {
  const relativePath = toRelativeWorkspacePath(path);
  const sandboxExists = await getSandboxIdFromRegistry(conversationId);
  if (sandboxExists) {
    try {
      await removeSandboxFile(conversationId, relativePath);
    } catch (err) {
      console.warn(
        `[conversation-storage] sandbox delete failed for ${relativePath}:`,
        err instanceof Error ? err.message : err,
      );
    }
  }
  if (isUnderBackupEligibleDir(relativePath)) {
    void deleteSessionFileFromS3(conversationId, relativePath).catch(
      (err: unknown) => {
        console.warn(
          `[conversation-storage] S3 delete failed for ${relativePath}:`,
          err instanceof Error ? err.message : err,
        );
      },
    );
  }
};

/**
 * Mirror sandbox-side changes (created/modified/deleted) to S3. Called
 * after `python` / `bash` runs from `runInSandbox`'s before/after diff.
 *
 * Only paths under backup-eligible top-level dirs (`attachments/`,
 * `outputs/`) are mirrored — agents writing under `drive/` or
 * `skills/` is a no-op (read-only contract by convention).
 */
export const mirrorSandboxChanges = async (
  conversationId: string,
  artifacts: SandboxArtifact[],
  deletedPaths: string[],
): Promise<void> => {
  await Promise.all([
    ...artifacts.map(async (artifact) => {
      if (!isUnderBackupEligibleDir(artifact.path)) return;
      try {
        const bytes = await readSandboxFile(conversationId, artifact.path);
        queueS3Backup(conversationId, artifact.path, bytes);
      } catch (err) {
        console.warn(
          `[conversation-storage] mirror read failed for ${artifact.path}:`,
          err instanceof Error ? err.message : err,
        );
      }
    }),
    ...deletedPaths.map(async (deleted) => {
      if (!isUnderBackupEligibleDir(deleted)) return;
      void deleteSessionFileFromS3(conversationId, deleted).catch(
        (err: unknown) => {
          console.warn(
            `[conversation-storage] S3 delete failed for ${deleted}:`,
            err instanceof Error ? err.message : err,
          );
        },
      );
    }),
  ]);
};

/**
 * Drop every byte for this conversation: the entire S3 session
 * folder. The sandbox itself (if any) is owned by the E2B layer
 * (`releaseSandbox`, `killSandbox`) and naturally expires under
 * autoPause — we don't kill it here.
 *
 * Used by the conversation DELETE handler.
 */
export const deleteConversationStorage = async (
  conversationId: string,
): Promise<void> => {
  await deleteSessionFolderFromS3(conversationId);
};

