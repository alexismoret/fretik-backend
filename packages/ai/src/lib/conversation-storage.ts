// S3 BACKUP QUEUE (per-process)                                 //
// ============================================================ //

/**
 * Per-`(conv, path)` in-flight backup chain. Serialises backups so
 * two parallel writes from the same replica land in order on S3.
 *
 * Cross-replica races on the same path use last-write-wins (S3
 * putObject is atomic). If that becomes a real problem a Redis lock
 * keyed on `(conv, path)` can be added later.
 *
 * Fire-and-forget: callers never `await` the chain. Failures are
 * logged inside `uploadSessionFile`.
 */
const queueS3Backup = (
  conversationId: string,
  relativePath: string,
  bytes: Uint8Array,
  contentType?: string,
): void => {
  const key = `${conversationId}::${relativePath}`;
  const previous = backupChains.get(key) ?? Promise.resolve();
  const next = previous
    .catch(() => {
      // Already logged at the failure site; swallow so subsequent
      // backups in the same chain still run.
    })
    .then(async () => {
      await uploadSessionFile(conversationId, relativePath, bytes, contentType);
    });
  backupChains.set(key, next);
  void next.finally(() => {
    if (backupChains.get(key) === next) {
      backupChains.delete(key);
    }
  });
};

