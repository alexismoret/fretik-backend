export interface AttachUserFileResult {
  /** Path relative to `/workspace` (e.g. `attachments/foo.pdf`). */
  path: string;
  /** Absolute sandbox path (`/workspace/attachments/foo.pdf`). */
  absolutePath: string;
}

/**
 * Attach a user-uploaded file to the conversation. Writes it to the
 * sandbox under `attachments/{filename}` and uploads the same bytes
 * to S3 — synchronously, so a downstream consumer (e.g. the OCR
 * preprocessor that hands a presigned URL to Mistral) cannot race the
 * backup and see a 404.
 *
 * The filename is sanitised; the caller (chat-files upload service)
 * is expected to have already deduped against existing names.
 *
 * `contentType` should be the `file.type` from the multipart upload
 * boundary so Scaleway serves the object with the right Content-Type
 * (Mistral OCR otherwise can refuse the fetched blob).
 */
export const attachUserFile = async (
  conversationId: string,
  filename: string,
  bytes: Uint8Array | string,
  contentType?: string,
): Promise<AttachUserFileResult> => {
  const sanitisedFilename = sanitizeSessionPath(filename);
  const relativePath = `${WORKSPACE_DIRS.attachments}/${sanitisedFilename}`;
  await writeFile(conversationId, relativePath, bytes, {
    contentType,
    awaitBackup: true,
  });
  return {
    path: relativePath,
    absolutePath: `${WORKSPACE_ROOT}/${relativePath}`,
  };
};

interface WriteFileOptions {
  /**
   * Content-Type for the S3 backup. Threaded down to `putObject` so
   * Scaleway serves the object with the proper MIME (otherwise it
   * defaults to `application/octet-stream`). Pass when known —
   * `file.type` from multipart uploads, `text/markdown` for sidecars.
   */
  contentType?: string;
  /**
   * If `true`, awaits the S3 backup before returning. Required when a
   * downstream step will presign + fetch the object immediately
   * (e.g. user attachments → OCR). Defaults to `false` (fire-and-
   * forget) for hot-path writes like sidecars and tool outputs.
   */
  awaitBackup?: boolean;
}

/**
 * Write arbitrary bytes to the sandbox at the given workspace-relative
 * path. Triggers an S3 backup for paths under `attachments/` or
 * `outputs/`. Used internally for OCR sidecars and persisted
 * tool-output envelopes.
 */
export const writeFile = async (
  conversationId: string,
  path: string,
  bytes: Uint8Array | string,
  options: WriteFileOptions = {},
): Promise<void> => {
  await ensureSandboxReady(conversationId);
  const buffer =
    typeof bytes === "string" ? new TextEncoder().encode(bytes) : bytes;
  const relativePath = toRelativeWorkspacePath(path);
  await writeSandboxFile(conversationId, relativePath, buffer);
  if (isUnderBackupEligibleDir(relativePath)) {
    if (options.awaitBackup) {
      await uploadSessionFile(
        conversationId,
        relativePath,
        buffer,
        options.contentType,
      );
    } else {
      queueS3Backup(conversationId, relativePath, buffer, options.contentType);
    }
  }
};

/**
 * Read raw bytes from the sandbox. Throws if the file is missing.
 * Bootstrap (incl. S3 restore) runs lazily on first access so a
 * sandbox recreated after expiry transparently sees its old files.
 */
export const readFile = async (
  conversationId: string,
  path: string,
): Promise<Uint8Array> => {
  await ensureSandboxReady(conversationId);
  const relativePath = toRelativeWorkspacePath(path);
  return readSandboxFile(conversationId, relativePath);
};

/**
 * Read a file as UTF-8 text. Convenience wrapper around `readFile`.
 */
export const readFileText = async (
  conversationId: string,
  path: string,
): Promise<string> => {
  const bytes = await readFile(conversationId, path);
  return new TextDecoder().decode(bytes);
};

/**
 * Check whether a file exists in the sandbox.
 */
export const fileExists = async (
  conversationId: string,
  path: string,
): Promise<boolean> => {
  await ensureSandboxReady(conversationId);
  return sandboxFileExists(conversationId, toRelativeWorkspacePath(path));
};

/**
 * List files in the sandbox. With no `subdir`, lists the entire
 * workspace tree (filtered to regular files). With `subdir`, narrows
 * to that directory.
 */
export const listFiles = async (
  conversationId: string,
  subdir?: string,
): Promise<SandboxFileEntry[]> => {
  await ensureSandboxReady(conversationId);
  return listSandboxFiles(conversationId, subdir);
};

/**
 * Delete a file from the sandbox and from S3 if it was backup-eligible.
 * Best-effort on both sides — failure to delete locally still attempts
 * the remote delete.
 */
export const deleteFile = async (
  conversationId: string,
  path: string,
): Promise<void> => {
  await ensureSandboxReady(conversationId);
  const relativePath = toRelativeWorkspacePath(path);
  try {
    await removeSandboxFile(conversationId, relativePath);
  } catch (err) {
    console.warn(
      `[conversation-storage] sandbox delete failed for ${relativePath}:`,
      err instanceof Error ? err.message : err,
    );
  }
  if (isUnderBackupEligibleDir(relativePath)) {
    void deleteSessionFileFromS3(conversationId, relativePath).catch(
      (err: unknown) => {
        console.warn(
          `[conversation-storage] S3 delete failed for ${relativePath}:`,
          err instanceof Error ? err.message : err,
        );
      },
    );
  }
};

/**
 * Mirror sandbox-side changes (created/modified/deleted) to S3. Called
 * after `python` / `bash` runs from `runInSandbox`'s before/after diff.
 *
 * Only paths under backup-eligible top-level dirs (`attachments/`,
 * `outputs/`) are mirrored — agents writing under `drive/` or
 * `skills/` is a no-op (read-only contract by convention).
 */
export const mirrorSandboxChanges = async (
  conversationId: string,
  artifacts: SandboxArtifact[],
  deletedPaths: string[],
): Promise<void> => {
  await Promise.all([
    ...artifacts.map(async (artifact) => {
      if (!isUnderBackupEligibleDir(artifact.path)) return;
      try {
        const bytes = await readSandboxFile(conversationId, artifact.path);
        queueS3Backup(conversationId, artifact.path, bytes);
      } catch (err) {
        console.warn(
          `[conversation-storage] mirror read failed for ${artifact.path}:`,
          err instanceof Error ? err.message : err,
        );
      }
    }),
    ...deletedPaths.map(async (deleted) => {
      if (!isUnderBackupEligibleDir(deleted)) return;
      void deleteSessionFileFromS3(conversationId, deleted).catch(
        (err: unknown) => {
          console.warn(
            `[conversation-storage] S3 delete failed for ${deleted}:`,
            err instanceof Error ? err.message : err,
          );
        },
      );
    }),
  ]);
};

/**
 * Drop every byte for this conversation: the entire S3 session
 * folder. The sandbox itself (if any) is owned by the E2B layer
 * (`releaseSandbox`, `killSandbox`) and naturally expires under
 * autoPause — we don't kill it here.
 *
 * Used by the conversation DELETE handler.
 */
export const deleteConversationStorage = async (
  conversationId: string,
): Promise<void> => {
  await deleteSessionFolderFromS3(conversationId);
};

