/**
 * Public wrapper around the lazy bootstrap. Tools that drive their own
 * sandbox interactions (`python`, `bash`) should call this once before
 * they run code so the workspace layout (`attachments/`, `outputs/`,
 * `skills/`, …) is guaranteed to exist and any S3-backed files are
 * already restored. Idempotent — cheap on subsequent calls (in-process
 * `Set` hit).
 */
export const prepareSandbox = async (
  conversationId: string,
): Promise<SandboxLease> => ensureSandboxReady(conversationId);

/**
 * Pull any attachments uploaded since this replica last restored them
 * into an already-bootstrapped sandbox. Attachments are written to S3
 * only at attach time (no eager E2B push), so a sandbox this replica
 * bootstrapped on an earlier turn won't have files added between turns.
 * The Redis-backed generation counter (bumped on every attach) tells us
 * whether a re-restore is needed — a single Redis GET in the steady
 * state, and `restoreFromS3` is idempotent (skip-on-exists) when it
 * does run.
 */
const reconcileAttachments = async (
  sandboxId: string,
  conversationId: string,
): Promise<void> => {
  const currentGen = await getAttachmentGeneration(conversationId);
  const restoredGen = restoredAttachmentGen.get(sandboxId) ?? 0;
  if (currentGen <= restoredGen) return;
  await restoreFromS3(conversationId);
  restoredAttachmentGen.set(sandboxId, currentGen);
};

/**
 * Idempotent: returns the lease, ensuring the underlying sandbox has
 * been bootstrapped (dirs + skills + S3 restore) for our process AND
 * that any attachment uploaded since the last restore is present.
 */
const ensureSandboxReady = async (
  conversationId: string,
): Promise<SandboxLease> => {
  const lease = await acquireSandbox(conversationId);

  // In-process fast path — still reconcile attachments uploaded since
  // we bootstrapped (cheap Redis GET unless a new file landed).
  if (initializedSandboxes.has(lease.sandboxId)) {
    await reconcileAttachments(lease.sandboxId, conversationId);
    return lease;
  }

  // In-process dedup.
  let pending = inFlightInits.get(lease.sandboxId);
  if (!pending) {
    pending = bootstrapWithLock(lease, conversationId)
      .then(() => {
        initializedSandboxes.add(lease.sandboxId);
      })
      .finally(() => {
        inFlightInits.delete(lease.sandboxId);
      });
    inFlightInits.set(lease.sandboxId, pending);
  }
  await pending;
  // Bootstrap's restoreFromS3 already pulled everything currently in S3;
  // mark this generation covered so the next code run skips the redundant
  // restore until a further attach bumps the counter.
  await reconcileAttachments(lease.sandboxId, conversationId);
  return lease;
};

const bootstrapWithLock = async (
  lease: SandboxLease,
  conversationId: string,
): Promise<void> => {
  // Cheap lock-free check: if another replica already wrote the
  // marker, we can skip the heavy bootstrap and just run S3 restore
  // (idempotent — skips files already present).
  if (await sandboxFileExists(conversationId, FRETIK_INIT_MARKER)) {
    await restoreFromS3(conversationId);
    return;
  }

  const lockToken = randomUUID();
  const gotLock = await acquireSandboxBootstrapLock(lease.sandboxId, lockToken);

  if (!gotLock) {
    // Another replica is bootstrapping. Wait for the marker.
    for (let i = 0; i < BOOTSTRAP_POLL_MAX_ITERATIONS; i++) {
      await sleep(BOOTSTRAP_POLL_INTERVAL_MS);
      if (await sandboxFileExists(conversationId, FRETIK_INIT_MARKER)) {
        await restoreFromS3(conversationId);
        return;
      }
    }
    // Lock holder seemingly wedged or dead — try once more now that
    // the TTL should be expiring.
    const retryToken = randomUUID();
    const retried = await acquireSandboxBootstrapLock(
      lease.sandboxId,
      retryToken,
    );
    if (!retried) {
      throw new Error(
        `Timed out waiting for sandbox bootstrap on ${lease.sandboxId}`,
      );
    }
    try {
      if (await sandboxFileExists(conversationId, FRETIK_INIT_MARKER)) {
        await restoreFromS3(conversationId);
        return;
      }
      await runFullBootstrap(conversationId);
    } finally {
      await releaseSandboxBootstrapLock(lease.sandboxId, retryToken);
    }
    return;
  }

  try {
    // Re-check under the lock — the previous holder may have just
    // finished between our exists check and the lock acquire.
    if (await sandboxFileExists(conversationId, FRETIK_INIT_MARKER)) {
      await restoreFromS3(conversationId);
      return;
    }
    await runFullBootstrap(conversationId);
  } finally {
    await releaseSandboxBootstrapLock(lease.sandboxId, lockToken);
  }
};

const runFullBootstrap = async (conversationId: string): Promise<void> => {
  // Bootstrap is dominated by per-call E2B round-trip latency
  // (~1-2 s baseline for any writeSandboxFile + tar -xzf pair,
  // regardless of payload size). Sequentially that totals 6-8 s on
  // cold start. Every push targets a DISJOINT top-level sub-directory
  // under /workspace, and the staging tarballs land at distinct /tmp
  // paths, so we fan them out with `Promise.all`. Worst case becomes
  // the slowest single push (~2 s) instead of the sum.
  //
  // Safety audit (parallel-safe pre-conditions):
  //  - `createWorkspaceDirs` is awaited BEFORE the fan-out → all
  //    top-level dirs exist before any push runs.
  //  - Top-level destinations are disjoint: bundled skills →
  //    /workspace/skills/{pdf,xlsx,…}, team skills →
  //    /workspace/skills/<team-slug>, external-app skills →
  //    /workspace/skills/<providerKey>, SDK → /workspace/fretik_apps,
  //    S3 restore → /workspace/{attachments,outputs}. Names cannot
  //    collide under current conventions (provider keys are not used
  //    by bundled skills; a team-uploaded skill named after a provider
  //    would already collide in the sequential version, so the risk
  //    isn't introduced by parallelism).
  //  - Each push owns its /tmp tarball filename (different per push,
  //    `rm -f` at the end of its own extract command).
  //  - E2B's daemon serialises filesystem mutations inside the
  //    container; parallel HTTP requests only eliminate the
  //    round-trip dead time, they don't produce concurrent `tar`
  //    processes that fight over the FS.
  //
  // `touchFretikInitMarker` STAYS sequential after the fan-out — its
  // presence is the cross-replica signal that bootstrap finished
  // (see `bootstrapWithLock`).
  await createWorkspaceDirs(conversationId);
  await Promise.all([
    pushBundledSkills(conversationId),
    pushTeamSkills(conversationId),
    pushExternalAppsSdk(conversationId),
    pushExternalAppProviderSkills(conversationId),
    restoreFromS3(conversationId),
  ]);
  // MCP overlay runs AFTER the fan-out, not inside it: it writes stubs into
  // /workspace/fretik_apps/ — the same top-level dir `pushExternalAppsSdk`
  // untars into — so keeping it out of the parallel batch avoids sharing a
  // destination and guarantees the base `_runtime.py`/`__init__.py` are
  // already in place. Soft-fails internally, so it never blocks the marker.
  await pushMcpConnectionOverlay(conversationId);
  await touchFretikInitMarker(conversationId);
};

/**
 * One `mkdir -p` instead of eight `files.makeDir` calls. The directory names
 * are compile-time constants from `WORKSPACE_DIRS`, so there is nothing to
 * quote and nothing a caller can inject. `mkdir -p` is idempotent, which is
 * what the per-call "ignore already-exists" handling was working around.
 */
const createWorkspaceDirs = async (conversationId: string): Promise<void> => {
  const dirs = [
    WORKSPACE_DIRS.attachments,
    WORKSPACE_DIRS.outputs,
    WORKSPACE_DIRS.outputsPersisted,
    WORKSPACE_DIRS.runs,
    WORKSPACE_DIRS.drive,
    WORKSPACE_DIRS.skills,
    WORKSPACE_DIRS.context,
    WORKSPACE_DIRS.memories,
  ].map((dir) => `${WORKSPACE_ROOT}/${dir}`);
  try {
    const result = await execSandboxCommand(
      conversationId,
      `mkdir -p ${dirs.join(" ")}`,
    );
    if (result.exitCode !== 0) {
      console.warn(
        `[conversation-storage] workspace mkdir exited ${result.exitCode.toString()}: ${result.stderr.trim()}`,
      );
    }
  } catch (err) {
    console.warn(
      "[conversation-storage] workspace mkdir failed:",
      err instanceof Error ? err.message : err,
    );
  }
};

/**
 * Push the bundled-skills bundle into `/workspace/skills/` for this
 * conversation. Two-step protocol:
 *
 *   1. Upload the pre-built gzipped tarball to `/tmp/fretik-skills.tar.gz`
 *      (single E2B file write — the bytes are cached in-process so the
 *      filesystem walk + gzip cost is paid once per service boot).
 *   2. `tar -xzf` it into `/workspace/skills/` and `rm` the tarball.
 *
 * Bootstrap is idempotent at the outer layer (`runFullBootstrap` only
 * fires when the `.fretik-init` marker is absent), so this body assumes
 * a clean target. We still pass `--no-overwrite-dir` defensively in
 * case the directory exists with leftover files from a half-completed
 * previous attempt — `tar` falls back to merging in-place which is the
 * idempotent behaviour we want.
 *
 * Soft-fail: a tarball or extract error is logged but not thrown. The
 * agent will then see `_No skills enabled for this team._` on its next
 * turn, which is recoverable on the next conversation bootstrap.
 */
const pushBundledSkills = async (conversationId: string): Promise<void> => {
  const bytes = await getSkillsTarballBytes();
  if (!bytes) {
    console.warn(
      "[conversation-storage] no skills tarball available — skipping skills push",
    );
    return;
  }

  const startedAt = Date.now();
  try {
    await writeSandboxFile(conversationId, SKILLS_TARBALL_SANDBOX_PATH, bytes);
  } catch (err) {
    console.warn(
      "[conversation-storage] failed to upload skills tarball:",
      err instanceof Error ? err.message : err,
    );
    return;
  }

  const skillsDir = `${WORKSPACE_ROOT}/${WORKSPACE_DIRS.skills}`;
  // `set -e` makes the line abort on the first failing step so we surface
  // a meaningful stderr in the catch below instead of a silent skip.
  const extractCommand = [
    "set -e",
    `mkdir -p ${skillsDir}`,
    `tar -xzf ${SKILLS_TARBALL_SANDBOX_PATH} -C ${skillsDir}`,
    `rm -f ${SKILLS_TARBALL_SANDBOX_PATH}`,
  ].join(" && ");

  try {
    const result = await execSandboxCommand(conversationId, extractCommand);
    if (result.exitCode !== 0) {
      console.warn(
        `[conversation-storage] skills tarball extract failed (exit=${result.exitCode.toString()}): ${result.stderr.trim()}`,
      );
      return;
    }
  } catch (err) {
    console.warn(
      "[conversation-storage] skills tarball extract threw:",
      err instanceof Error ? err.message : err,
    );
    return;
  }

  const duration = Date.now() - startedAt;
  console.log(
    `[conversation-storage] pushed skills tarball: ${(bytes.byteLength / 1024).toFixed(1)} KB, ${duration.toString()}ms (upload+extract)`,
  );
};

/**
 * Push every enabled team-uploaded skill into `/workspace/skills/<slug>/SKILL.md`.
 *
 * Bundled skills come in as a single pre-built tarball (see
 * `pushBundledSkills` above) which is fast and idempotent. Team-uploaded
 * skills are low-volume (cap at ~30 per team) and change at human pace,
 * so per-file `writeSandboxFile` calls are simpler than maintaining a
 * second per-team tarball cache — and E2B creates parent directories
 * automatically on `files.write`.
 *
 * Materialised SKILL.md format mirrors the bundled on-disk layout
 * (YAML frontmatter + body) so the chatbot reads both kinds the same
 * way via `bash cat /workspace/skills/<slug>/SKILL.md`.
 *
 * Soft-fail: any error per skill is logged and skipped — the catalogue
 * in the system prompt still lists the skill but `bash cat` will
 * return ENOENT, which the LLM handles gracefully. We avoid hard
 * failures here so a single bad skill doesn't break the whole
 * conversation bootstrap.
 *
 * Resolves teamId from `aiConversations` inside the shared service —
 * keeps `runFullBootstrap`'s signature small (`conversationId`-only)
 * and avoids threading teamId through every call site.
 */
const pushTeamSkills = async (conversationId: string): Promise<void> => {
  let entries: Awaited<
    ReturnType<typeof listEnabledTeamUploadedSkillsWithBodyForConversation>
  >;
  try {
    entries =
      await listEnabledTeamUploadedSkillsWithBodyForConversation(
        conversationId,
      );
  } catch (err) {
    console.warn(
      "[conversation-storage] failed to list team-uploaded skills:",
      err instanceof Error ? err.message : err,
    );
    return;
  }

  if (entries.length === 0) return;

  const startedAt = Date.now();
  const skillsDir = `${WORKSPACE_ROOT}/${WORKSPACE_DIRS.skills}`;
  const encoder = new TextEncoder();

  // `files.write` creates the parent directories it needs, so a batched write
  // is enough — one request for the whole set. The per-file `allSettled` path
  // is kept as the fallback: a batch is all-or-nothing, and one malformed
  // skill should not cost the team every other one.
  const files = entries.map((entry) => ({
    path: `${skillsDir}/${entry.name}/SKILL.md`,
    bytes: encoder.encode(materializeTeamSkillMd(entry)),
  }));

  let written = files.length;
  try {
    await writeSandboxFiles(conversationId, files);
  } catch (err) {
    console.warn(
      "[conversation-storage] team skills batch write failed, retrying one by one:",
      err instanceof Error ? err.message : err,
    );
    const results = await Promise.allSettled(
      files.map((file) =>
        writeSandboxFile(conversationId, file.path, file.bytes),
      ),
    );
    written = results.filter((r) => r.status === "fulfilled").length;
    for (const [i, r] of results.entries()) {
      if (r.status === "rejected") {
        const entry = entries[i];
        console.warn(
          `[conversation-storage] failed to write team skill "${entry?.name ?? "?"}":`,
          r.reason instanceof Error ? r.reason.message : r.reason,
        );
      }
    }
  }

  const duration = Date.now() - startedAt;
  console.log(
    `[conversation-storage] pushed ${written.toString()}/${entries.length.toString()} team skills, ${duration.toString()}ms`,
  );
};

