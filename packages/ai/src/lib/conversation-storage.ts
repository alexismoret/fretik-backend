/**
 * Public wrapper around the lazy bootstrap. Tools that drive their own
 * sandbox interactions (`python`, `bash`) should call this once before
 * they run code so the workspace layout (`attachments/`, `outputs/`,
 * `skills/`, …) is guaranteed to exist and any S3-backed files are
 * already restored. Idempotent — cheap on subsequent calls (in-process
 * `Set` hit).
 */
export const prepareSandbox = async (
  conversationId: string,
): Promise<SandboxLease> => ensureSandboxReady(conversationId);

/**
 * Idempotent: returns the lease, ensuring the underlying sandbox has
 * been bootstrapped (dirs + skills + S3 restore) for our process.
 */
const ensureSandboxReady = async (
  conversationId: string,
): Promise<SandboxLease> => {
  const lease = await acquireSandbox(conversationId);

  // In-process fast path.
  if (initializedSandboxes.has(lease.sandboxId)) return lease;

  // In-process dedup.
  let pending = inFlightInits.get(lease.sandboxId);
  if (!pending) {
    pending = bootstrapWithLock(lease, conversationId)
      .then(() => {
        initializedSandboxes.add(lease.sandboxId);
      })
      .finally(() => {
        inFlightInits.delete(lease.sandboxId);
      });
    inFlightInits.set(lease.sandboxId, pending);
  }
  await pending;
  return lease;
};

const bootstrapWithLock = async (
  lease: SandboxLease,
  conversationId: string,
): Promise<void> => {
  // Cheap lock-free check: if another replica already wrote the
  // marker, we can skip the heavy bootstrap and just run S3 restore
  // (idempotent — skips files already present).
  if (await sandboxFileExists(conversationId, FRETIK_INIT_MARKER)) {
    await restoreFromS3(conversationId);
    return;
  }

  const lockToken = randomUUID();
  const gotLock = await acquireSandboxBootstrapLock(lease.sandboxId, lockToken);

  if (!gotLock) {
    // Another replica is bootstrapping. Wait for the marker.
    for (let i = 0; i < BOOTSTRAP_POLL_MAX_ITERATIONS; i++) {
      await sleep(BOOTSTRAP_POLL_INTERVAL_MS);
      if (await sandboxFileExists(conversationId, FRETIK_INIT_MARKER)) {
        await restoreFromS3(conversationId);
        return;
      }
    }
    // Lock holder seemingly wedged or dead — try once more now that
    // the TTL should be expiring.
    const retryToken = randomUUID();
    const retried = await acquireSandboxBootstrapLock(
      lease.sandboxId,
      retryToken,
    );
    if (!retried) {
      throw new Error(
        `Timed out waiting for sandbox bootstrap on ${lease.sandboxId}`,
      );
    }
    try {
      if (await sandboxFileExists(conversationId, FRETIK_INIT_MARKER)) {
        await restoreFromS3(conversationId);
        return;
      }
      await runFullBootstrap(conversationId);
    } finally {
      await releaseSandboxBootstrapLock(lease.sandboxId, retryToken);
    }
    return;
  }

  try {
    // Re-check under the lock — the previous holder may have just
    // finished between our exists check and the lock acquire.
    if (await sandboxFileExists(conversationId, FRETIK_INIT_MARKER)) {
      await restoreFromS3(conversationId);
      return;
    }
    await runFullBootstrap(conversationId);
  } finally {
    await releaseSandboxBootstrapLock(lease.sandboxId, lockToken);
  }
};

const runFullBootstrap = async (conversationId: string): Promise<void> => {
  await createWorkspaceDirs(conversationId);
  await pushBundledSkills(conversationId);
  await restoreFromS3(conversationId);
  await touchFretikInitMarker(conversationId);
};

const createWorkspaceDirs = async (conversationId: string): Promise<void> => {
  await Promise.all(
    [
      WORKSPACE_DIRS.attachments,
      WORKSPACE_DIRS.outputs,
      WORKSPACE_DIRS.outputsPersisted,
      WORKSPACE_DIRS.drive,
      WORKSPACE_DIRS.skills,
      WORKSPACE_DIRS.context,
      WORKSPACE_DIRS.memory,
    ].map(async (dir) => {
      try {
        await makeSandboxDir(conversationId, dir);
      } catch (err) {
        console.warn(
          `[conversation-storage] makeDir failed for ${dir}:`,
          err instanceof Error ? err.message : err,
        );
      }
    }),
  );
};

/**
 * Push the bundled-skills bundle into `/workspace/skills/` for this
 * conversation. Two-step protocol:
 *
 *   1. Upload the pre-built gzipped tarball to `/tmp/fretik-skills.tar.gz`
 *      (single E2B file write — the bytes are cached in-process so the
 *      filesystem walk + gzip cost is paid once per service boot).
 *   2. `tar -xzf` it into `/workspace/skills/` and `rm` the tarball.
 *
 * Bootstrap is idempotent at the outer layer (`runFullBootstrap` only
 * fires when the `.fretik-init` marker is absent), so this body assumes
 * a clean target. We still pass `--no-overwrite-dir` defensively in
 * case the directory exists with leftover files from a half-completed
 * previous attempt — `tar` falls back to merging in-place which is the
 * idempotent behaviour we want.
 *
 * Soft-fail: a tarball or extract error is logged but not thrown. The
 * agent will then see `_No skills enabled for this team._` on its next
 * turn, which is recoverable on the next conversation bootstrap.
 */
const pushBundledSkills = async (conversationId: string): Promise<void> => {
  const bytes = await getSkillsTarballBytes();
  if (!bytes) {
    console.warn(
      "[conversation-storage] no skills tarball available — skipping skills push",
    );
    return;
  }

  const startedAt = Date.now();
  try {
    await writeSandboxFile(conversationId, SKILLS_TARBALL_SANDBOX_PATH, bytes);
  } catch (err) {
    console.warn(
      "[conversation-storage] failed to upload skills tarball:",
      err instanceof Error ? err.message : err,
    );
    return;
  }

  const skillsDir = `${WORKSPACE_ROOT}/${WORKSPACE_DIRS.skills}`;
  // `set -e` makes the line abort on the first failing step so we surface
  // a meaningful stderr in the catch below instead of a silent skip.
  const extractCommand = [
    "set -e",
    `mkdir -p ${skillsDir}`,
    `tar -xzf ${SKILLS_TARBALL_SANDBOX_PATH} -C ${skillsDir}`,
    `rm -f ${SKILLS_TARBALL_SANDBOX_PATH}`,
  ].join(" && ");

  try {
    const result = await execSandboxCommand(conversationId, extractCommand);
    if (result.exitCode !== 0) {
      console.warn(
        `[conversation-storage] skills tarball extract failed (exit=${result.exitCode.toString()}): ${result.stderr.trim()}`,
      );
      return;
    }
  } catch (err) {
    console.warn(
      "[conversation-storage] skills tarball extract threw:",
      err instanceof Error ? err.message : err,
    );
    return;
  }

  const duration = Date.now() - startedAt;
  console.log(
    `[conversation-storage] pushed skills tarball: ${(bytes.byteLength / 1024).toFixed(1)} KB, ${duration.toString()}ms (upload+extract)`,
  );
};

const touchFretikInitMarker = async (conversationId: string): Promise<void> => {
  try {
    await writeSandboxFile(
      conversationId,
      FRETIK_INIT_MARKER,
      new TextEncoder().encode(new Date().toISOString()),
    );
  } catch (err) {
    console.warn(
      "[conversation-storage] failed to write init marker:",
      err instanceof Error ? err.message : err,
    );
  }
};

const restoreFromS3 = async (conversationId: string): Promise<void> => {
  const paths = await listSessionPaths(conversationId);
  if (paths.length === 0) return;

  await Promise.all(
    paths.map(async (relativePath) => {
      // Backup-eligible only — we never restore bookkeeping dirs.
      if (!isUnderBackupEligibleDir(relativePath)) return;

      // Idempotent: skip if the sandbox already has the file.
      if (await sandboxFileExists(conversationId, relativePath)) return;

      const bytes = await readSessionFile(conversationId, relativePath);
      if (!bytes) {
        console.warn(
          `[conversation-storage] restoreFromS3: missing GET for ${conversationId}/${relativePath}`,
        );
        return;
      }
      try {
        await writeSandboxFile(conversationId, relativePath, bytes);
      } catch (err) {
        console.warn(
          `[conversation-storage] restoreFromS3: write failed for ${relativePath}:`,
          err instanceof Error ? err.message : err,
        );
      }
    }),
  );
};

